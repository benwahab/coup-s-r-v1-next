type Dict = typeof dict.fr;
type Key = keyof Dict;

/** Variables d'interpolation acceptées : `{name}` dans le template est
 *  remplacé par `String(vars.name)`. Utilisation typique :
 *    t("ticketCount", { count: 3 })  →  "3 tickets"                            */
export type TVars = Record<string, string | number>;

/** Remplace tous les motifs `{name}` par la valeur correspondante. */
function interpolate(template: string, vars?: TVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : `{${name}}`,
  );
}

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: Key, vars?: TVars) => string;
}
const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");
  useEffect(() => {
    const stored =
      typeof window !== "undefined" ? (localStorage.getItem("lonani.lang") as Lang | null) : null;
    if (stored === "fr" || stored === "en") setLangState(stored);
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("lonani.lang", l);
  };
  const t = (k: Key, vars?: TVars) => interpolate(dict[lang][k], vars);
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const c = useContext(Ctx);
  if (!c) throw new Error("useI18n must be used inside I18nProvider");
  return c;
}
